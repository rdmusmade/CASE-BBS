export function getAutoGeneratedTag(category: MemberCategory, existingMembers: any[] = []): string {
  const prefixMap: Record<MemberCategory, string> = {
    FOOTING: 'FTG',
    BEAM: 'BM',
    COLUMN: 'COL',
    SLAB: 'SLB',
    RCC_PARDI: 'SW',
    PLAIN_PCC_MESH: 'PCC',
    STAIRCASE: 'STR',
    WATER_TANK: 'WT',
  };
  const prefix = prefixMap[category] || 'MBR';
  const existingCount = existingMembers.filter((m) => {
    const t = m.memberType || m.category;
    return t === category || (m.memberTag && m.memberTag.startsWith(prefix));
  }).length;
  const nextNum = existingCount + 1;
  return `${prefix}-${nextNum.toString().padStart(2, '0')}`;
}

